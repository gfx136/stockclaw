const resources: Record<Lang, Record<string, string>> = { zh, en };

export type Lang = 'zh' | 'en';

function resolve(pref: LanguagePref): Lang {
  if (pref === 'zh' || pref === 'en') return pref;
  return getSystemLang();
}

/** 当前语言（模块级，t() 同步读） */
let currentLang: Lang = 'zh';

/** 取文案（无参数） */
export function t(key: Key): string {
  return resources[currentLang][key] ?? resources.zh[key] ?? String(key);
}

/** 取文案（带 {n} 等占位参数） */
export function tf(key: Key, params: Record<string, string | number>): string {
  let s = t(key);
  for (const [k, v] of Object.entries(params)) {
    s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return s;
}

/** 当前语言（供日期格式等使用） */
export function getCurrentLang(): Lang {
  return currentLang;
}

/** React hook：订阅语言变化，返回 t 函数与当前语言 */
export function useT(): { t: typeof t; tf: typeof tf; lang: Lang } {
  const [lang, setLang] = useState<Lang>(currentLang);
  useEffect(() => {
    let active = true;
    const load = async () => {
      const pref = await getLanguage();
      const l = resolve(pref);
      currentLang = l;
      if (active) setLang(l);
    };
    load();
    const unsub = onLanguageChange(load);
    return () => {
      active = false;
      unsub();
    };
  }, []);
  return { t, tf, lang };
}